import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,readFile,mkdir,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
test('local editor saves persistent drafts, rejects stale/foreign writes, restores and never modifies public content',async t=>{
 const mod=await import('./tools/editor/server.mjs').catch(()=>null);
 assert.ok(mod?.startEditor,'local editor is not implemented');
 const root=await mkdtemp(join(tmpdir(),'perth-editor-test-'));
 const before=await readFile('public/zh/about/index.html','utf8');
 let server=await mod.startEditor({host:'127.0.0.1',port:0,draftRoot:root});
 t.after(async()=>{await server.close();});
 const api=async(path,init={})=>fetch(server.url+'api/'+path,init);
 let token=(await (await api('session')).json()).token;
 const headers={'x-editor-token':token};
 const pages=await (await api('pages',{headers})).json();assert.equal(pages.length,69);
 const model=await (await api('draft/about.html',{headers})).json();
 const field=model.fields.find(f=>!f.locked&&f.kind==='text');assert.ok(field);
 const save=async(changes,revision,extra={})=>api('draft/about.html',{method:'PUT',headers:{...headers,origin:new URL(server.url).origin,'content-type':'application/json',...extra},body:JSON.stringify({baseHash:model.baseHash,expectedRevision:revision,changes})});
 assert.equal((await save({[field.id]:'本地测试中文说明'},0)).status,200);
 assert.equal((await save({[field.id]:'不能覆盖'},0)).status,409);
 assert.equal((await save({[field.id]:'跨站'},1,{origin:'https://example.com'})).status,403);
 assert.equal((await save({unknown:'未知字段'},1)).status,400);
 const html=await (await api('preview/about.html?locale=zh-Hans',{headers})).text();assert.match(html,/本地测试中文说明/);assert.doesNotMatch(html,/<script[^>]+googletagmanager/);
 assert.equal((await fetch(new URL('/api/enquiry',server.url),{method:'POST'})).status,403);
 assert.equal((await fetch(new URL('/.env',server.url))).status,404);
 await server.close();server=await mod.startEditor({host:'127.0.0.1',port:0,draftRoot:root});
 token=(await (await api('session')).json()).token;headers['x-editor-token']=token;
 assert.equal((await (await api('draft/about.html',{headers})).json()).draft.changes[field.id],'本地测试中文说明');
 assert.equal((await save({[field.id]:'第二版本地中文'},1)).status,200);
 const restored=await api('restore/about.html',{method:'POST',headers:{...headers,origin:new URL(server.url).origin,'content-type':'application/json'},body:JSON.stringify({historyRevision:1,expectedRevision:2})});assert.equal(restored.status,200);assert.equal((await restored.json()).revision,3);
 assert.equal(await readFile('public/zh/about/index.html','utf8'),before);
});
test('an interrupted history write does not permanently block the next save',async()=>{
 const {saveDraft,readDraft}=await import('./tools/editor/store.mjs');
 const root=await mkdtemp(join(tmpdir(),'perth-editor-crash-'));
 const old=await saveDraft(root,{pageId:'about.html',expectedRevision:0,baseHash:'test',changes:{field:'第一修订'}});
 await mkdir(join(root,'history','about.html'),{recursive:true});
 await writeFile(join(root,'history','about.html','2.json'),JSON.stringify({...old,revision:2,changes:{field:'中断的第二修订'}}));
 const next=await saveDraft(root,{pageId:'about.html',expectedRevision:1,baseHash:'test',changes:{field:'恢复后的修订'}});
 assert.equal(next.changes.field,'恢复后的修订');assert.ok(next.revision>2);assert.equal((await readDraft(root,'about.html')).revision,next.revision);
});
